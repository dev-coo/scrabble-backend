# ─────────────────────────────────────────────────────────────
# 스크래블 게임 기초 데이터 — 칩(타일) 구성과 보드 배열
#
# 여기 있는 값은 **게임의 규칙 그 자체**입니다. 방마다 달라지지도 않고,
# 사람이 바꾸지도 않습니다. E 가 12개인 것은 스크래블이라는 게임이
# 그렇게 정해져 있기 때문입니다.
#
# 왜 DB 가 아니라 코드에 두는가:
#   DB 는 **바뀌는 것**을 담는 곳입니다. 누가 어느 방에 있는지, 무슨 말을
#   했는지처럼요. 규칙은 바뀌지 않으므로 DB 에 넣으면 얻는 것 없이
#   "매번 꺼내 와야 하는 번거로움"만 생깁니다. 게다가 DB 에 두면 누군가
#   실수로 고쳤을 때 **게임 규칙이 조용히 달라집니다.**
#   반대로 "이 방의 가방에 지금 몇 개 남았는지"는 방마다 다르고 계속
#   변하므로 그건 나중에 DB 로 가야 합니다.
#
# 왜 main.py 가 아니라 이 파일인가:
#   main.py 는 이미 1300줄이 넘습니다. 데이터는 로직과 성격이 달라서
#   (읽을 일은 많고 고칠 일은 거의 없음) 갈라 두면 양쪽 다 보기 쉽습니다.
#
# 확인:  .venv/bin/python game_data.py
# ─────────────────────────────────────────────────────────────
from typing import Dict, List, Tuple

# ─────────────────────────────────────────────────────────────
# 1. 칩(타일) 구성 — 영어 표준 100개
#
# (글자, 개수, 점수) 세 가지를 한 줄에 적었습니다. 셋은 항상 같이
# 쓰이는 값이라 따로 떼어 놓으면 서로 어긋나기 쉽습니다.
#
# 개수와 점수가 반대로 움직이는 게 보이실 겁니다 — E 는 12개인데 1점,
# Q 는 1개인데 10점입니다. 흔한 글자는 많이 넣고 싸게, 귀한 글자는 조금
# 넣고 비싸게 한 것입니다. 이게 스크래블의 균형입니다.
# ─────────────────────────────────────────────────────────────

# 빈 타일을 나타내는 글자.
#
# 실제 타일에는 아무것도 안 적혀 있고, 낼 때 "이건 S 로 치겠다"처럼
# 정합니다. JSON 으로 주고받아야 해서 뭔가 한 글자는 필요한데, 알파벳을
# 쓰면 진짜 그 글자와 구별이 안 되므로 알파벳이 아닌 `?` 를 씁니다.
BLANK = "?"

# (글자, 개수, 점수)
TILE_DISTRIBUTION: Tuple[Tuple[str, int, int], ...] = (
    # 1점 — 가장 흔한 글자들
    ("E", 12, 1),
    ("A", 9, 1),
    ("I", 9, 1),
    ("O", 8, 1),
    ("N", 6, 1),
    ("R", 6, 1),
    ("T", 6, 1),
    ("L", 4, 1),
    ("S", 4, 1),
    ("U", 4, 1),
    # 2점
    ("D", 4, 2),
    ("G", 3, 2),
    # 3점
    ("B", 2, 3),
    ("C", 2, 3),
    ("M", 2, 3),
    ("P", 2, 3),
    # 4점
    ("F", 2, 4),
    ("H", 2, 4),
    ("V", 2, 4),
    ("W", 2, 4),
    ("Y", 2, 4),
    # 5점
    ("K", 1, 5),
    # 8점
    ("J", 1, 8),
    ("X", 1, 8),
    # 10점 — 가장 귀한 글자들
    ("Q", 1, 10),
    ("Z", 1, 10),
    # 빈 타일. 아무 글자로나 쓸 수 있는 대신 **0점**입니다.
    # 편한 만큼 점수를 포기하는 것이라 이 0 은 실수가 아닙니다.
    (BLANK, 2, 0),
)

# 글자 하나가 몇 점인지 빨리 찾기 위한 표. 위 목록에서 만들어지므로
# 두 곳을 따로 고칠 일이 없습니다. (한쪽만 고쳐서 어긋나는 사고 방지)
TILE_POINTS: Dict[str, int] = {
    letter: points for letter, _count, points in TILE_DISTRIBUTION
}

# 가방에 들어가는 타일 전체 개수.
TOTAL_TILES = sum(count for _letter, count, _points in TILE_DISTRIBUTION)

# 한 사람이 손에 들고 있는 타일 수. 스크래블 표준은 7개입니다.
#
# 왜 7개인가(게임 설계상): 너무 적으면 만들 수 있는 단어가 없어 답답하고,
# 너무 많으면 아무 때나 좋은 단어가 나와서 재미가 없습니다.
RACK_SIZE = 7


def build_bag() -> List[str]:
    """타일 100개가 순서대로 들어 있는 **가방 하나**를 새로 만들어 줍니다.

    예: `['E','E','E',...,'A','A',...,'?','?']`

    ⚠️ **섞지 않았습니다.** 섞는 것은 "게임을 시작할 때 하는 일"이고,
    여기는 "무엇이 들어 있는가"만 담당합니다. 이 함수가 섞어서 주면
    나중에 "왜 매번 다르지?"를 이 파일에서 찾게 되는데, 그건 여기 있으면
    안 되는 성질입니다.

    매번 **새 목록을 만들어** 돌려주는 것도 중요합니다. 하나를 만들어
    돌려쓰면 A 방에서 타일을 꺼낼 때 B 방의 가방도 같이 줄어듭니다.
    """
    bag: List[str] = []
    for letter, count, _points in TILE_DISTRIBUTION:
        bag.extend([letter] * count)
    return bag


# ─────────────────────────────────────────────────────────────
# 2. 보드 배열 — 15 × 15
#
# 보드는 그냥 빈 격자가 아니라, **칸마다 성격이 다릅니다.** 어떤 칸에
# 타일을 놓으면 그 글자 점수가 2배가 되고, 어떤 칸은 단어 전체가 3배가
# 됩니다. 그 성격을 미리 적어 둔 것이 아래 표입니다.
#
# 이 배열이 담는 것은 **칸의 성격뿐**입니다. "지금 어느 칸에 무슨 타일이
# 놓여 있는가"는 여기 없습니다. 그건 방마다 다르고 매 순간 바뀌는 값이라
# 나중에 따로 다룹니다. 규칙과 현재 상태를 한 표에 섞으면, 게임이 끝날
# 때마다 규칙을 다시 만들어야 합니다.
#
# 칸 종류:
#   TW = Triple Word   단어 점수 3배
#   DW = Double Word   단어 점수 2배
#   TL = Triple Letter 글자 점수 3배
#   DL = Double Letter 글자 점수 2배
#   ST = Start         한가운데 별. 첫 단어는 반드시 여기를 지나야 합니다.
#                      점수는 DW 와 같게 칩니다.
#   "" = 아무것도 아닌 보통 칸
#
# 왜 숫자가 아니라 글자 두 개로 적는가: `3` 이라고만 적으면 그게 글자
# 3배인지 단어 3배인지 알 수 없습니다. 보드를 눈으로 읽을 수 있어야
# 잘못 적힌 칸을 찾아낼 수 있습니다.
# ─────────────────────────────────────────────────────────────
BOARD_SIZE = 15

# 한가운데 칸의 좌표. 크기에서 계산하므로 보드가 바뀌어도 따라옵니다.
CENTER = BOARD_SIZE // 2  # 7

# 아래 표는 **위에서 아래로** 한 줄씩입니다. `BOARD_LAYOUT[줄][칸]` 으로
# 찾습니다. 둘 다 0 부터 셉니다. 예) 왼쪽 맨 위 = BOARD_LAYOUT[0][0] = "TW"
#
# 점 하나(`.`)는 보통 칸입니다. 빈 문자열로 적으면 줄이 어긋난 걸 눈으로
# 찾을 수 없어서, 자리를 차지하는 글자로 적어 두고 아래에서 바꿉니다.
_BOARD_ROWS = (
    "TW  .   .   DL  .   .   .   TW  .   .   .   DL  .   .   TW",
    ".   DW  .   .   .   TL  .   .   .   TL  .   .   .   DW  . ",
    ".   .   DW  .   .   .   DL  .   DL  .   .   .   DW  .   . ",
    "DL  .   .   DW  .   .   .   DL  .   .   .   DW  .   .   DL",
    ".   .   .   .   DW  .   .   .   .   .   DW  .   .   .   . ",
    ".   TL  .   .   .   TL  .   .   .   TL  .   .   .   TL  . ",
    ".   .   DL  .   .   .   DL  .   DL  .   .   .   DL  .   . ",
    "TW  .   .   DL  .   .   .   ST  .   .   .   DL  .   .   TW",
    ".   .   DL  .   .   .   DL  .   DL  .   .   .   DL  .   . ",
    ".   TL  .   .   .   TL  .   .   .   TL  .   .   .   TL  . ",
    ".   .   .   .   DW  .   .   .   .   .   DW  .   .   .   . ",
    "DL  .   .   DW  .   .   .   DL  .   .   .   DW  .   .   DL",
    ".   .   DW  .   .   .   DL  .   DL  .   .   .   DW  .   . ",
    ".   DW  .   .   .   TL  .   .   .   TL  .   .   .   DW  . ",
    "TW  .   .   DL  .   .   .   TW  .   .   .   DL  .   .   TW",
)

# 위 그림을 실제로 쓸 수 있는 배열로 바꿉니다. `.` 은 보통 칸이라
# 빈 문자열이 됩니다.
BOARD_LAYOUT: Tuple[Tuple[str, ...], ...] = tuple(
    tuple("" if cell == "." else cell for cell in row.split())
    for row in _BOARD_ROWS
)

# 각 칸이 무슨 뜻인지. 프론트엔드가 보드를 그리고 설명을 띄울 때 씁니다.
#
# `multiplier`(배수)와 `applies_to`(무엇에 걸리는가)를 나눠 둔 이유:
# "3배"라는 숫자만으로는 글자에 거는지 단어에 거는지 알 수 없어서,
# 점수를 계산할 때 결국 칸 이름을 하나하나 따져야 합니다.
PREMIUM_LEGEND: Dict[str, Dict[str, object]] = {
    "TW": {"name": "단어 3배", "multiplier": 3, "applies_to": "word"},
    "DW": {"name": "단어 2배", "multiplier": 2, "applies_to": "word"},
    "TL": {"name": "글자 3배", "multiplier": 3, "applies_to": "letter"},
    "DL": {"name": "글자 2배", "multiplier": 2, "applies_to": "letter"},
    # 시작 칸은 점수로는 DW 와 똑같이 칩니다. 다만 "첫 단어는 여기를
    # 지나야 한다"는 규칙이 따로 붙어 있어서 이름을 나눠 두었습니다.
    "ST": {"name": "시작 칸 (단어 2배)", "multiplier": 2, "applies_to": "word"},
}


# ─────────────────────────────────────────────────────────────
# 3. 스스로 검사하기
#
# 아래 검사는 **이 파일을 불러오는 순간 자동으로 돕니다.** 위 표를 손으로
# 적었기 때문에 오타가 날 수 있는데, 타일이 99개이거나 보드 한 줄이 14칸인
# 것은 **눈으로는 절대 못 찾습니다.** 그대로 두면 게임이 이상하게 돌아가고
# 나중에 원인을 찾느라 한참 헤매게 됩니다.
#
# 서버가 아예 안 켜지는 편이 훨씬 낫습니다. 고장이 눈에 띄니까요.
# ─────────────────────────────────────────────────────────────
assert TOTAL_TILES == 100, f"타일은 100개여야 하는데 {TOTAL_TILES}개입니다"
assert len(build_bag()) == 100, "가방에 든 타일 수가 100개가 아닙니다"

assert len(BOARD_LAYOUT) == BOARD_SIZE, (
    f"보드는 {BOARD_SIZE}줄이어야 하는데 {len(BOARD_LAYOUT)}줄입니다"
)
for _i, _row in enumerate(BOARD_LAYOUT):
    assert len(_row) == BOARD_SIZE, (
        f"보드 {_i}번째 줄이 {BOARD_SIZE}칸이 아니라 {len(_row)}칸입니다"
    )

# 적어 둔 적 없는 칸 이름이 섞여 들어가지 않았는지. ("DDL" 같은 오타)
for _row in BOARD_LAYOUT:
    for _cell in _row:
        assert _cell == "" or _cell in PREMIUM_LEGEND, f"모르는 칸 종류: {_cell!r}"

# 한가운데는 반드시 시작 칸이어야 합니다. 여기가 어긋나면 첫 수를 어디에
# 둬야 하는지가 통째로 틀어집니다.
assert BOARD_LAYOUT[CENTER][CENTER] == "ST", "한가운데가 시작 칸이 아닙니다"


if __name__ == "__main__":
    # 직접 실행하면 지금 구성이 어떤 모습인지 보여줍니다.
    print(f"타일 {TOTAL_TILES}개 / 손에 드는 수 {RACK_SIZE}개\n")

    by_points: Dict[int, List[str]] = {}
    for letter, count, points in TILE_DISTRIBUTION:
        by_points.setdefault(points, []).append(f"{letter}×{count}")
    for points in sorted(by_points):
        print(f"  {points:2}점  {'  '.join(by_points[points])}")

    print(f"\n보드 {BOARD_SIZE}×{BOARD_SIZE}")
    for row in BOARD_LAYOUT:
        print("  " + " ".join(cell.rjust(2) if cell else " ·" for cell in row))

    counts: Dict[str, int] = {}
    for row in BOARD_LAYOUT:
        for cell in row:
            if cell:
                counts[cell] = counts.get(cell, 0) + 1
    print("\n특수 칸 개수")
    for kind, n in sorted(counts.items()):
        print(f"  {kind} ({PREMIUM_LEGEND[kind]['name']}): {n}칸")
